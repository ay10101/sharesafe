"""
ShareSafe — Resilient LLM Wrapper.

Provides safe, optional LLM completions with:
- Graceful deterministic fallback to None on errors or missing credentials.
- Prompt-hash caching of successful completions.
- Strict bounded timeouts (default 8s).
- Local structured-output validation with at most one retry on schema failure.
- Zero secret exposure in logs or error traces.
- Enrichment-only behavior (never part of core authorization decisions).
"""
from __future__ import annotations

import hashlib
import json
import logging
import os
import socket
import time
import urllib.error
import urllib.request
from typing import Any, Dict, List, Optional, Type, Union

from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------------
logger = logging.getLogger("sharesafe.ai.llm")

# ---------------------------------------------------------------------------
# Models
# ---------------------------------------------------------------------------
class LLMResult(BaseModel):
    """Result of a successful LLM completion."""
    content: str = Field(description="Raw text content generated by the model.")
    structured_data: Optional[Any] = Field(
        default=None,
        description="Parsed and validated structured data when json_schema was provided.",
    )
    model: str = Field(default="", description="The model identifier used for completion.")
    cached: bool = Field(default=False, description="True if response was served from cache.")
    prompt_tokens: Optional[int] = Field(default=None, description="Prompt token count if reported.")
    completion_tokens: Optional[int] = Field(default=None, description="Completion token count if reported.")


# ---------------------------------------------------------------------------
# In-Memory Cache
# ---------------------------------------------------------------------------
_CACHE: Dict[str, LLMResult] = {}


def clear_cache() -> None:
    """Clear the in-memory response cache. Useful for tests and memory resets."""
    _CACHE.clear()


# ---------------------------------------------------------------------------
# Configuration Helpers
# ---------------------------------------------------------------------------
def _get_api_key() -> Optional[str]:
    """Retrieve the API key from environment variables (never logged)."""
    return os.environ.get("OPENAI_API_KEY") or os.environ.get("LLM_API_KEY")


def _get_base_url() -> str:
    """Retrieve the base URL, defaulting to standard OpenAI endpoint."""
    return os.environ.get("OPENAI_BASE_URL") or os.environ.get("LLM_BASE_URL") or "https://api.openai.com/v1"


def _get_model() -> str:
    """Retrieve the default model identifier."""
    return os.environ.get("LLM_MODEL") or os.environ.get("OPENAI_MODEL") or "gpt-4o-mini"


# ---------------------------------------------------------------------------
# Cache Key Construction
# ---------------------------------------------------------------------------
def _compute_cache_key(
    prompt: str,
    system: Optional[str],
    json_schema: Optional[Union[Type[BaseModel], Dict[str, Any]]],
    base_url: str,
    model: str,
) -> str:
    """Compute a deterministic SHA-256 cache key from the full effective request."""
    schema_repr = ""
    if json_schema is not None:
        if isinstance(json_schema, type) and issubclass(json_schema, BaseModel):
            schema_repr = json.dumps(json_schema.model_json_schema(), sort_keys=True)
        elif isinstance(json_schema, dict):
            schema_repr = json.dumps(json_schema, sort_keys=True)
        else:
            schema_repr = str(json_schema)

    elements = [
        f"base_url={base_url}",
        f"model={model}",
        f"system={system or ''}",
        f"prompt={prompt}",
        f"schema={schema_repr}",
    ]
    raw_key = "||".join(elements)
    return hashlib.sha256(raw_key.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# JSON & Schema Helpers
# ---------------------------------------------------------------------------
def _strip_markdown_fence(text: str) -> str:
    """Strip optional markdown code block fences around JSON text."""
    s = text.strip()
    if s.startswith("```"):
        lines = s.splitlines()
        if lines and lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        s = "\n".join(lines).strip()
    return s


def _validate_structured_output(
    content: str,
    json_schema: Union[Type[BaseModel], Dict[str, Any]],
) -> Any:
    """
    Validate JSON string content against a Pydantic model or JSON Schema dict.
    Raises ValueError on invalid JSON or validation mismatch.
    """
    cleaned = _strip_markdown_fence(content)
    try:
        parsed = json.loads(cleaned)
    except Exception as e:
        raise ValueError(f"Content is not valid JSON: {e}") from e

    if isinstance(json_schema, type) and issubclass(json_schema, BaseModel):
        try:
            return json_schema.model_validate(parsed)
        except Exception as e:
            raise ValueError(f"Schema validation failed: {e}") from e

    if isinstance(json_schema, dict):
        try:
            import jsonschema
        except ImportError as e:
            raise ValueError(
                "JSON Schema validator is unavailable: 'jsonschema' package is not installed."
            ) from e
        try:
            jsonschema.validate(instance=parsed, schema=json_schema)
            return parsed
        except Exception as e:
            raise ValueError(f"Schema validation failed: {e}") from e

    raise ValueError(f"Unsupported json_schema type: {type(json_schema)}")


# ---------------------------------------------------------------------------
# Network Call
# ---------------------------------------------------------------------------
def _post_chat_completion(
    base_url: str,
    api_key: str,
    model: str,
    messages: List[Dict[str, str]],
    timeout: float,
    response_format: Optional[Dict[str, str]] = None,
) -> Optional[Dict[str, Any]]:
    """
    Execute HTTP POST to /chat/completions endpoint using standard library urllib.
    Returns parsed JSON response dict, or None on any failure.
    """
    url = f"{base_url.rstrip('/')}/chat/completions"
    payload: Dict[str, Any] = {
        "model": model,
        "messages": messages,
    }
    if response_format:
        payload["response_format"] = response_format

    try:
        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url=url,
            data=data,
            headers={
                "Content-Type": "application/json",
                "Authorization": f"Bearer {api_key}",
                "User-Agent": "ShareSafe-AI/1.0",
            },
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = resp.read().decode("utf-8")
            return json.loads(body)
    except urllib.error.HTTPError as e:
        if e.code == 429:
            logger.warning("LLM call failed: rate limit exceeded (HTTP 429).")
        elif e.code in (401, 403):
            logger.warning("LLM call failed: authentication or authorization error (HTTP %d).", e.code)
        else:
            logger.warning("LLM call failed with HTTP status %d.", e.code)
        return None
    except (urllib.error.URLError, socket.timeout, TimeoutError) as e:
        logger.warning("LLM call failed: network timeout or connection error: %s", type(e).__name__)
        return None
    except json.JSONDecodeError:
        logger.warning("LLM call failed: provider returned malformed non-JSON response.")
        return None
    except Exception as e:
        logger.warning("LLM call failed with unexpected error: %s", type(e).__name__)
        return None


# ---------------------------------------------------------------------------
# Public Interface
# ---------------------------------------------------------------------------
def complete(
    prompt: str,
    *,
    system: Optional[str] = None,
    json_schema: Optional[Union[Type[BaseModel], Dict[str, Any]]] = None,
    timeout: float = 8.0,
) -> Optional[LLMResult]:
    """
    Generate an LLM completion with fallback, caching, and structured validation.

    Parameters:
    - prompt: User or task prompt string.
    - system: Optional system instruction prompt.
    - json_schema: Optional Pydantic BaseModel class or JSON schema dict for output validation.
    - timeout: Maximum request duration in seconds (defaults to 8.0).

    Returns:
    - LLMResult on success, or None on any failure/fallback.
    """
    # Validate timeout parameter
    try:
        timeout_budget = float(timeout)
    except (TypeError, ValueError):
        logger.warning("LLM call skipped: invalid timeout parameter %r.", timeout)
        return None

    if timeout_budget <= 0.0:
        logger.warning("LLM call skipped: timeout must be positive (got %r).", timeout)
        return None

    api_key = _get_api_key()
    if not api_key:
        logger.debug("LLM skipped: no API key found in environment.")
        return None

    base_url = _get_base_url()
    model = _get_model()

    # 1. Check in-memory cache
    cache_key = _compute_cache_key(prompt, system, json_schema, base_url, model)
    if cache_key in _CACHE:
        logger.info("LLM cache hit for key %s...", cache_key[:10])
        hit = _CACHE[cache_key]
        return LLMResult(
            content=hit.content,
            structured_data=hit.structured_data,
            model=hit.model,
            cached=True,
            prompt_tokens=hit.prompt_tokens,
            completion_tokens=hit.completion_tokens,
        )

    # 2. Build initial message sequence
    messages: List[Dict[str, str]] = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})

    response_format = {"type": "json_object"} if json_schema is not None else None

    # Track elapsed time across potential attempts using a monotonic clock
    start_time = time.monotonic()

    # 3. Call provider (Attempt 1)
    logger.info("LLM call dispatching (model=%s, timeout=%ss, prompt_bytes=%d)", model, timeout_budget, len(prompt.encode("utf-8")))
    res_data = _post_chat_completion(
        base_url=base_url,
        api_key=api_key,
        model=model,
        messages=messages,
        timeout=timeout_budget,
        response_format=response_format,
    )
    if not res_data:
        return None

    # Parse response content
    try:
        choice = res_data["choices"][0]
        content = choice["message"]["content"]
        if content is None:
            return None
    except (KeyError, IndexError, TypeError):
        logger.warning("LLM response missing expected choices[0].message.content structure.")
        return None

    usage = res_data.get("usage") or {}
    prompt_tokens = usage.get("prompt_tokens")
    completion_tokens = usage.get("completion_tokens")

    # 4. Handle plain text completion (no schema required)
    if json_schema is None:
        result = LLMResult(
            content=content,
            structured_data=None,
            model=model,
            cached=False,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
        )
        _CACHE[cache_key] = result
        return result

    # 5. Handle structured validation with at most one retry
    val_err_msg = ""
    try:
        validated_data = _validate_structured_output(content, json_schema)
        result = LLMResult(
            content=content,
            structured_data=validated_data,
            model=model,
            cached=False,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
        )
        _CACHE[cache_key] = result
        return result
    except ValueError as val_err:
        val_err_msg = str(val_err)
        logger.warning(
            "LLM structured output validation failed on initial attempt: %s.",
            val_err_msg,
        )
        # If the validator is fundamentally unavailable, do not attempt retry
        if "JSON Schema validator is unavailable" in val_err_msg:
            return None

    # Calculate remaining timeout budget for retry using monotonic clock
    elapsed = time.monotonic() - start_time
    remaining_budget = timeout_budget - elapsed
    MIN_RETRY_TIMEOUT = 0.1  # Minimum seconds required to attempt network retry
    if remaining_budget < MIN_RETRY_TIMEOUT:
        logger.warning(
            "LLM structured output retry skipped: timeout budget exhausted (elapsed=%.2fs, remaining=%.2fs).",
            elapsed,
            remaining_budget,
        )
        return None

    # Retry attempt with explicit correction guidance and remaining budget
    retry_prompt = (
        f"{prompt}\n\n"
        f"[System Note: Your previous response was invalid JSON or did not match the schema: {val_err_msg}. "
        f"Return ONLY valid JSON complying with the schema.]"
    )
    retry_messages = list(messages)
    retry_messages[-1] = {"role": "user", "content": retry_prompt}

    logger.info("LLM structured output retrying with remaining budget (timeout=%.2fs)", remaining_budget)
    retry_data = _post_chat_completion(
        base_url=base_url,
        api_key=api_key,
        model=model,
        messages=retry_messages,
        timeout=remaining_budget,
        response_format=response_format,
    )
    if not retry_data:
        return None

    try:
        retry_choice = retry_data["choices"][0]
        retry_content = retry_choice["message"]["content"]
        if retry_content is None:
            return None
    except (KeyError, IndexError, TypeError):
        return None

    retry_usage = retry_data.get("usage") or {}
    retry_p_tokens = retry_usage.get("prompt_tokens") or prompt_tokens
    retry_c_tokens = retry_usage.get("completion_tokens") or completion_tokens

    try:
        validated_retry_data = _validate_structured_output(retry_content, json_schema)
        result = LLMResult(
            content=retry_content,
            structured_data=validated_retry_data,
            model=model,
            cached=False,
            prompt_tokens=retry_p_tokens,
            completion_tokens=retry_c_tokens,
        )
        _CACHE[cache_key] = result
        return result
    except ValueError as second_err:
        logger.warning("LLM structured output validation failed on retry: %s. Falling back to None.", str(second_err))
        return None
